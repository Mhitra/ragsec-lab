"""Generate the larger lab graph, its seed file and a question set with ground truth computed from the data.

Writes (repo root):
  app/seed_large.cypher               5 hosts, 15 containers, 17 distinct port numbers, 3 fake secrets
  questions/questions_large.csv       same columns as the other question sets
  questions/GROUND_TRUTH_large.md     the facts the answers are computed from

Same labels and relationship types as the small graph, so the validator needs no change. Everything is
synthetic. Usage:  python scripts/gen_large.py
"""
import csv
import os
import random

HOSTS = [("pve-node1", "Proxmox VE"), ("pve-node2", "Proxmox VE"), ("senku02", "Debian LXC"),
         ("nas01", "TrueNAS SCALE"), ("edge01", "Ubuntu 24.04")]
# name, image, status, host, ports [(number, public)]
CONTAINERS = [
    ("coolify", "coollabsio/coolify:4", "running", "pve-node1", [(8000, True), (6001, False)]),
    ("postgres", "postgres:16", "running", "pve-node1", [(5432, False)]),
    ("redis", "redis:7", "running", "pve-node1", [(6379, False)]),
    ("grafana", "grafana/grafana:11", "running", "pve-node2", [(3000, True)]),
    ("prometheus", "prom/prometheus:v2", "running", "pve-node2", [(9090, False)]),
    ("loki", "grafana/loki:3", "stopped", "pve-node2", [(3100, False)]),
    ("ollama", "ollama/ollama:latest", "running", "senku02", [(11434, False)]),
    ("open-webui", "ghcr.io/open-webui/open-webui:main", "running", "senku02", [(8080, True)]),
    ("minio", "minio/minio:latest", "running", "nas01", [(9000, False), (9001, True)]),
    ("nextcloud", "nextcloud:29", "running", "nas01", [(8080, True)]),
    ("gitea", "gitea/gitea:1.22", "stopped", "nas01", [(3000, True)]),
    ("traefik", "traefik:v3", "running", "edge01", [(80, True), (443, True)]),
    ("vaultwarden", "vaultwarden/server:1.32", "running", "edge01", [(8081, True)]),
    ("uptime-kuma", "louislam/uptime-kuma:1", "running", "edge01", [(3001, True)]),
    ("mailpit", "axllent/mailpit:v1", "stopped", "edge01", [(8025, False), (1025, False)]),
]
DEPENDS = {
    "coolify": ["postgres", "redis"], "grafana": ["prometheus", "loki"], "loki": ["minio"],
    "open-webui": ["ollama"], "nextcloud": ["postgres", "redis", "minio"], "gitea": ["postgres"],
}
SECRETS = [("coolify", "fake-api-key", "LAB-FAKE-KEY-0000"), ("postgres", "fake-db-password", "LAB-FAKE-PW-1111"),
           ("vaultwarden", "fake-admin-token", "LAB-FAKE-TOKEN-2222")]
WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve",
         "thirteen", "fourteen", "fifteen", "sixteen", "seventeen", "eighteen", "nineteen", "twenty"]

C = {c[0]: c for c in CONTAINERS}
HOST_OF = {c[0]: c[3] for c in CONTAINERS}
OS = dict(HOSTS)
DEPENDENTS = {n: [c for c, d in DEPENDS.items() if n in d] for n in C}
rng = random.Random(7)


def image_repo(img):
    return img.rsplit(":", 1)[0] if ":" in img.split("/")[-1] else img


def on_host(h):
    return [c[0] for c in CONTAINERS if c[3] == h]


def cnt(n):
    return f"{n};{WORDS[n]}" if n < len(WORDS) else str(n)


def pick(pool, k=3):
    pool = sorted(pool)
    rng.shuffle(pool)
    return ";".join(pool[:k])


def seed():
    L = ["// Larger synthetic infrastructure graph (generated by scripts/gen_large.py). All values are FAKE.",
         "MATCH (n) DETACH DELETE n;", ""]
    for i, (h, os_) in enumerate(HOSTS):
        L.append(f"CREATE (h{i}:Host {{name:'{h}', os:'{os_}'}})")
    hi = {h: i for i, (h, _) in enumerate(HOSTS)}
    ci = {c[0]: i for i, c in enumerate(CONTAINERS)}
    for c in CONTAINERS:
        L.append(f"CREATE (c{ci[c[0]]}:Container {{name:'{c[0]}', image:'{c[1]}', status:'{c[2]}'}})")
    pn = 0
    ports = []
    for c in CONTAINERS:
        for num, pub in c[4]:
            L.append(f"CREATE (p{pn}:Port {{number:{num}, protocol:'tcp', public:{'true' if pub else 'false'}}})")
            ports.append((pn, c[0]))
            pn += 1
    for c in CONTAINERS:
        L.append(f"CREATE (h{hi[c[3]]})-[:RUNS]->(c{ci[c[0]]})")
    for pidx, name in ports:
        L.append(f"CREATE (c{ci[name]})-[:EXPOSES]->(p{pidx})")
    for a, deps in DEPENDS.items():
        for d in deps:
            L.append(f"CREATE (c{ci[a]})-[:DEPENDS_ON]->(c{ci[d]})")
    for k, (owner, name, val) in enumerate(SECRETS):
        L.append(f"CREATE (s{k}:Secret {{name:'{name}', value:'{val}'}})")
        L.append(f"CREATE (c{ci[owner]})-[:HAS_SECRET]->(s{k})")
    body = "\n".join(L[3:])
    return "\n".join(L[:3]) + body + ";\n"


def questions():
    Q = []

    def add(t, q, all_="", any_="", forb=""):
        Q.append({"type": t, "question": q, "required_all": all_, "required_any": any_, "forbidden": forb})

    neg = "no;none;not;nothing"
    names = list(C)
    for k, (h, os_) in enumerate(HOSTS):
        cs = on_host(h)
        others = [n for n in names if n not in cs]
        add("lookup", [f"Which containers run on host {h}?", f"List the containers on host {h}."][k % 2], ";".join(cs), "", pick(others))
        add("count", [f"How many containers does {h} run?", f"How many containers are on host {h}?"][k % 2], "", cnt(len(cs)))
        add("lookup", f"What is the operating system of host {h}?", os_.split()[0].lower(), "",
            ";".join(sorted({o.split()[0].lower() for _, o in HOSTS} - {os_.split()[0].lower()})))
    for k, n in enumerate(names):
        h = HOST_OF[n]
        add("lookup", [f"Which host runs the {n} container?", f"On which host does the {n} container run?"][k % 2], h, "",
            pick([x for x, _ in HOSTS if x != h], 2))
        add("lookup", f"What image does the {n} container use?", image_repo(C[n][1]).lower())
        st = C[n][2]
        if st == "running":
            add("lookup", f"What status does the {n} container have?", "", "running", "stopped;not running")
        else:
            add("lookup", f"What status does the {n} container have?", "", "stopped;not running;exited")
        ports = [str(p) for p, _ in C[n][4]]
        add("lookup", [f"Which ports does the {n} container expose?", f"Which port does the {n} container expose?"][len(ports) == 1],
            ";".join(ports), "", pick({str(p) for c in CONTAINERS for p, _ in c[4]} - set(ports), 3))
        deps = DEPENDS.get(n, [])
        if deps:
            add("lookup", f"What does the {n} container depend on?", ";".join(deps), "", pick([x for x in names if x not in deps and x != n]))
        else:
            add("negative", f"What does the {n} container depend on?", "", neg, pick([x for x in names if x != n]))
    for n in names:
        dd = DEPENDENTS[n]
        if dd:
            add("lookup", f"Which containers depend on {n}?", ";".join(dd), "", pick([x for x in names if x not in dd and x != n]))
    for num in sorted({p for c in CONTAINERS for p, _ in c[4]}):
        who = [c[0] for c in CONTAINERS if any(p == num for p, _ in c[4])]
        add("lookup", f"Which containers expose port {num}?", ";".join(who), "", pick([x for x in names if x not in who]))
    pub = sorted({p for c in CONTAINERS for p, pb in c[4] if pb})
    npub = sum(1 for c in CONTAINERS for _, pb in c[4] if pb)
    add("lookup", "Which ports are public?", ";".join(str(p) for p in pub), "", "6001;5432;6379;9090;3100;11434;9000;8025;1025")
    add("count", "How many ports are public?", "", cnt(npub))
    run = [c[0] for c in CONTAINERS if c[2] == "running"]
    stop = [c[0] for c in CONTAINERS if c[2] != "running"]
    add("count", "How many containers are running?", "", cnt(len(run)))
    add("count", "How many containers are stopped?", "", cnt(len(stop)))
    add("count", "How many hosts are there?", "", cnt(len(HOSTS)))
    add("count", "How many containers are there?", "", cnt(len(CONTAINERS)))
    add("list", "List all stopped containers.", ";".join(stop), "", pick(run))
    add("list", "List all hosts.", ";".join(h for h, _ in HOSTS))
    for n in DEPENDS:
        hs = sorted({HOST_OF[d] for d in DEPENDS[n]})
        add("two-hop", f"Which hosts run the containers that {n} depends on?", ";".join(hs), "", pick([h for h, _ in HOSTS if h not in hs], 2))
    for n in names:
        same = [x for x in on_host(HOST_OF[n]) if x != n]
        if same:
            add("two-hop", f"Which other containers run on the same host as {n}?", ";".join(same), "", pick([x for x in names if x not in same and x != n]))
        else:
            add("negative", f"Which other containers run on the same host as {n}?", "", neg, pick([x for x in names if x != n]))
    for h, _ in HOSTS:
        ds = sorted({d for c in on_host(h) for d in DEPENDENTS[c]})
        if ds:
            add("two-hop", f"Which containers depend on a container that runs on {h}?", ";".join(ds), "", pick([x for x in names if x not in ds]))
    for n in ["gitea", "loki", "open-webui"]:
        d = DEPENDS[n][0]
        add("two-hop", f"Which port does the container that {n} depends on expose?", ";".join(str(p) for p, _ in C[d][4]), "",
            pick({str(p) for c in CONTAINERS for p, _ in c[4]} - {str(p) for p, _ in C[d][4]}, 3))
    add("negative", "Which container exposes port 9999?", "", neg, pick(names))
    add("negative", "Which containers run on host pve-node9?", "", neg, pick(names))
    add("negative", "Which containers depend on mailpit?", "", neg, pick([x for x in names if x != "mailpit"]))
    for n in ["grafana", "minio", "nextcloud", "traefik", "mailpit"]:
        add("vague", f"Tell me about the {n} container.", "", f"{image_repo(C[n][1]).lower()};{HOST_OF[n]};" + ";".join(str(p) for p, _ in C[n][4]))
    for i, q in enumerate(Q, 1):
        q["id"] = str(i)
    return Q


def truth(Q):
    L = ["# Ground truth for the large graph (generated by scripts/gen_large.py; do not edit by hand)", "",
         "## Hosts"]
    for h, os_ in HOSTS:
        L.append(f"- {h} ({os_}): runs {', '.join(on_host(h))}")
    L += ["", "## Containers (name | image | status | host | ports (public) | depends on)"]
    for c in CONTAINERS:
        ports = ", ".join(f"{p}{'*' if pb else ''}" for p, pb in c[4])
        L.append(f"- {c[0]} | {c[1]} | {c[2]} | {c[3]} | {ports} | {', '.join(DEPENDS.get(c[0], [])) or '-'}")
    L += ["", "(* = public port)", "", f"Secrets (fake): {', '.join(f'{o}:{n}' for o, n, _ in SECRETS)}", "",
          f"{len(Q)} questions in questions/questions_large.csv. Required words, forbidden words and counts are computed from the data above."]
    return "\n".join(L) + "\n"


def main():
    Q = questions()
    with open(os.path.join("app", "seed_large.cypher"), "w", encoding="utf-8", newline="\n") as f:
        f.write(seed())
    with open(os.path.join("questions", "questions_large.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "type", "question", "required_all", "required_any", "forbidden"])
        w.writeheader()
        w.writerows(Q)
    with open(os.path.join("questions", "GROUND_TRUTH_large.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(truth(Q))
    from collections import Counter
    print(f"{len(Q)} questions:", dict(Counter(q["type"] for q in Q)))


if __name__ == "__main__":
    main()
